/**
 * Inlines the platform policy markdown into a TypeScript module.
 *
 * seed.ts originally read these files with `fs`, which does not exist on the
 * Cloudflare Worker, so seeding only ever worked in local dev. Regenerating
 * this module keeps one seed implementation that runs on both runtimes.
 *
 * Run: npm run seed:generate
 */

import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const KB_DIR = join(root, 'knowledge-base', 'platform-rules')
const OUT_FILE = join(root, 'backend', 'src', 'services', 'knowledge', 'seedData.ts')

const SEED_METADATA = {
  '01-selling-policies-code-of-conduct': {
    title: '亚马逊销售政策与卖家行为准则',
    platform: 'amazon',
    tags: ['亚马逊', '行为准则', '合规'],
  },
  '02-prohibited-restricted-products': {
    title: '亚马逊禁售与受限商品政策',
    platform: 'amazon',
    tags: ['亚马逊', '受限', '合规'],
  },
  '03-product-detail-page-rules': {
    title: '亚马逊商品详情页规则',
    platform: 'amazon',
    tags: ['亚马逊', '上架', '详情页'],
  },
  '04-product-safety-compliance': {
    title: '产品安全与合规认证',
    platform: 'amazon',
    tags: ['合规', '安全', '认证'],
  },
  '05-category-listing-restrictions': {
    title: '品类准入与分类审核',
    platform: 'amazon',
    tags: ['品类', '受限', '批准'],
  },
}

const files = readdirSync(KB_DIR).filter((f) => f.endsWith('.md')).sort()

const entries = files.map((file) => {
  const baseName = file.replace(/\.md$/, '')
  const meta = SEED_METADATA[baseName]
  if (!meta) throw new Error(`No SEED_METADATA entry for ${file}`)

  const content = readFileSync(join(KB_DIR, file), 'utf-8')
  return {
    title: meta.title,
    category: 'platform_rules',
    platform: meta.platform,
    tags: meta.tags,
    content,
  }
})

if (entries.length === 0) throw new Error(`No markdown files found in ${KB_DIR}`)

const body = entries
  .map(
    (e) => `  {
    title: ${JSON.stringify(e.title)},
    category: 'platform_rules',
    platform: ${JSON.stringify(e.platform)},
    tags: ${JSON.stringify(e.tags)},
    content: ${JSON.stringify(e.content)},
  },`,
  )
  .join('\n')

const output = `// AUTO-GENERATED by scripts/generate-seed-data.mjs — do not edit by hand.
// Source: knowledge-base/platform-rules/*.md
import type { KnowledgeCategory, Platform } from '../../types/index.js'

export interface SeedDoc {
  title: string
  content: string
  category: KnowledgeCategory
  platform?: Platform
  tags: string[]
}

export const SEED_DOCS: SeedDoc[] = [
${body}
]
`

writeFileSync(OUT_FILE, output, 'utf-8')
console.log(`Wrote ${entries.length} documents to ${OUT_FILE}`)
